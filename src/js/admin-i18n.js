let currentAdminLanguage = DEFAULT_ADMIN_LANGUAGE;

function resolveNestedKey(target, key){
  return String(key || "")
    .split(".")
    .reduce((accumulator, part) => (accumulator && accumulator[part] != null ? accumulator[part] : undefined), target);
}

function interpolate(template, params = {}){
  return String(template).replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ""));
}

function getStoredAdminLanguage(){
  try{
    const stored = window.localStorage.getItem(ADMIN_LANGUAGE_STORAGE_KEY);
    return SUPPORTED_ADMIN_LANGUAGES.has(stored) ? stored : DEFAULT_ADMIN_LANGUAGE;
  }catch{
    return DEFAULT_ADMIN_LANGUAGE;
  }
}

function persistAdminLanguage(language){
  try{
    window.localStorage.setItem(ADMIN_LANGUAGE_STORAGE_KEY, language);
  }catch{
    // Ignore storage failures.
  }
}

export function getAdminLanguage(){
  return currentAdminLanguage;
}

export function getAdminDirection(language = currentAdminLanguage){
  return language === "ar" ? "rtl" : "ltr";
}

export function getAdminLocale(language = currentAdminLanguage){
  return language === "ar" ? "ar-AE" : "en-US";
}

export function isAdminRTL(){
  return currentAdminLanguage === "ar";
}

export function adminT(key, params = {}){
  const languageDictionary = ADMIN_TRANSLATIONS[currentAdminLanguage] || ADMIN_TRANSLATIONS[DEFAULT_ADMIN_LANGUAGE];
  const fallbackDictionary = ADMIN_TRANSLATIONS[DEFAULT_ADMIN_LANGUAGE];
  const resolved = resolveNestedKey(languageDictionary, key) ?? resolveNestedKey(fallbackDictionary, key) ?? key;
  return interpolate(resolved, params);
}

export function setAdminLanguage(language, options = {}){
  const nextLanguage = SUPPORTED_ADMIN_LANGUAGES.has(language) ? language : DEFAULT_ADMIN_LANGUAGE;
  const shouldPersist = options.persist !== false;

  currentAdminLanguage = nextLanguage;

  if(shouldPersist){
    persistAdminLanguage(currentAdminLanguage);
  }

  document.dispatchEvent(new CustomEvent("admin:languagechange", {
    detail: {
      language: currentAdminLanguage,
      direction: getAdminDirection(currentAdminLanguage)
    }
  }));
}

export function initAdminI18n(){
  currentAdminLanguage = getStoredAdminLanguage();
  return currentAdminLanguage;
}

